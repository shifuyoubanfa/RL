# ---------------------------------------------------------------------------
# 3. 结论锚点拼装
# ---------------------------------------------------------------------------

def build_pool_anchor(pool_answers: list[str]) -> str:
    """把基座答案池里的极性、数字、日期拼成结构化锚点。

    抽取口径直接复用规则层的 :func:`src.rewards.rules.extract_facts`，跟评测那道
    "答案在池"门用的是同一套归一化。同口径是刻意的：改写的输入锚点和评测的判定靶子
    如果各用一套抽取，改出来的稿子会在评测里凭空掉分，而且查不出原因。

    :param pool_answers: 基座对该题的多条答案
    :return: 多行文本锚点；池子里抽不出任何事实时返回空串，调用方需要自己回退
    """
    from src.rewards.rules import extract_facts

    polarity: set[str] = set()
    values: set[str] = set()
    dates: set[str] = set()
    for answer in pool_answers or []:
        facts = extract_facts(answer)
        polarity |= facts["polarity"]
        values |= facts["value"]
        dates |= facts["date"]

    lines = []
    if polarity:
        lines.append("结论方向（只能落在这些极性上、不得相反）：" + "、".join(sorted(polarity)))
    if values:
        lines.append("可用的关键数字/金额/比例（只能用这些、不得新增）：" + "、".join(sorted(values)))
    if dates:
        lines.append("涉及日期/期限：" + "、".join(sorted(dates)))
    return "\n".join(lines)
