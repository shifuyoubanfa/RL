"""全链路用到的提示词，集中一处。

本模块在整条链路里的位置：数据构建和推理的输入端。改这里的任何一个字，都会改变训练数据
或评测口径，所以它们必须只有一个来源，不能各处复制。

三组：

1. **两套 system 提示**。基座模型原本被"基于参考问答对回答"这套 RAG 腔提示词训过，
   它的 think 里满是检索腔就是从这来的。链路要做的第一件事是换一套中性提示，
   不把这套腔调再烤进新模型。
2. **改写提示词**。冷启动阶段让裁判模型从"问题 + 事实依据 + 结论锚点"从头写一段自然推理。
3. **结论锚点拼装**。把基座答案池里抽出的极性、数字、日期拼成结构化文本塞进改写输入。

为什么锚点用结构化字段而不是直接给一段答案原文：给原文，改写模型就有东西可以复述；
给"极性=免征、数字=10万/9万"这种字段，它没有句子可抄，只能自己组织语言。这一步同时让
改写结果天然落在评测那道"答案在池"门的靶子上。
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 1. 两套 system 提示
# ---------------------------------------------------------------------------

# 基座模型自带的 RAG 腔提示词。检索腔的来源就是它。
# 只在两个地方用：重产基座输出（还原它真实行为）、跑基线评测（基线必须是它自己的分布）。
# 训练数据和训练后模型一律不用这套，否则等于把"我在查资料"的腔调再烤一遍。
RAG_SYSTEM_PROMPT = (
    "你是一个乐于助人的AI助手。你的任务是基于提供的参考问答对来回答用户的问题。工作流程：\n"
    "1. 仔细分析用户的问题\n"
    "2. 在参考问答对中搜索相关信息\n"
    "3. 基于参考内容组织回答，确保信息的准确性和相关性\n"
    "4. 如果参考问答对中有完全匹配的问题，直接使用对应的答案\n"
    "5. 如果参考问答对中没有直接匹配，但有关联信息，综合这些信息给出回答\n"
    "最后为用户提供答案推理过程和答案分别包含在<think> </think>和<answer> </answer>标签中，"
    "即<think>\n reasoning process here \n</think>\n\n<answer>\n answer here \n</answer>"
)

# 去检索腔的中性提示。从冷启动开始，训练数据和训练后模型推理全用它。
# 它仍然要求"严格依据已知资料"——去掉的是"罗列参考编号"这种表达方式，不是 grounding 本身。
# 这两件事必须分开：把 grounding 一起去掉，模型会开始凭记忆瞎编。
NEUTRAL_SYSTEM_PROMPT = (
    "你是一名专业的中文税务助手。你的推理与结论【必须严格依据已知资料中的事实、政策口径与数字】，"
    "不得凭记忆臆测，更不得给出与已知资料相矛盾的结论；只有已知资料未覆盖的细节才可谨慎使用常识补充。"
    "但表达上要像一位资深税务老师那样，把这些依据自然地融进思考、从问题一步步推导到结论，"
    "而不是罗列或复述「参考问答对」「资料编号」「检索结果」这类字样。"
    "把推理过程放在 <think> </think>、最终答案放在 <answer> </answer> 标签中，"
    "即<think>\n推理过程\n</think>\n\n<answer>\n答案\n</answer>。"
)


def system_for(served_model_name: str, base_served_name: str = "base") -> str:
    """按被请求的模型名挑 system 提示。

    这是一个**语义开关**，不是便利函数：数据构建和评测脚本会把当前要跑的模型 serve 成一个
    名字，本函数据此决定套哪套提示。serve 训练后的模型时如果名字误传成基座名，就会给它套
    RAG 腔提示——评测分会全错，而且错得看不出来（模型照样能生成，只是腔调被提示词拉回去了）。

    :param served_model_name: 推理服务里该模型的名字
    :param base_served_name: 基座在推理服务里的名字
    :return: 该用哪套 system 提示
    """
    return RAG_SYSTEM_PROMPT if served_model_name in (base_served_name, None, "") else NEUTRAL_SYSTEM_PROMPT


# ---------------------------------------------------------------------------
# 2. 冷启动改写提示词
# ---------------------------------------------------------------------------
#
# 一个更省事的做法是：把基座原来那段 think 喂给裁判模型，让它"改写得自然一点"。
# 那样写出来的东西会死死锚在原文措辞上——能改的只有词，句子骨架还是原来那副。
# 判分口径恰恰只数"有几句是把参考换个说法重讲一遍"，于是改出来的稿子分数上不去，
# 整条冷启动数据的质量被这个天花板压死。
#
# 所以这里不喂原 think，只给【问题 + 事实依据 + 结论锚点】，让它从问题出发自己推。
# 没有原文可锚，也就没有可复述的句子。
#
# 提示词里那对【坏 ✗ / 好 ✓】例子也是必需的：干净这一端本身方差就大（见标定表最后两档），
# 光讲抽象规则，模型对"什么叫复述"的理解会飘；给两句具体对照能把方差压下来。

REWRITE_SYSTEM = """你是一位资深税务师。现在给你一道税务题的【事实依据】（权威口径，含税率、金额、起征线、期限、适用条件等）、【用户问题】和这道题【已锁定的结论】。请你【从用户问题出发，像自己当场盘这道题一样，一步步推到那个结论】，写出一段第一人称的真实思考过程（think）。

判分的人只数一件事：你有几句是在"把事实依据里的某一段，换个说法重新讲了一遍"——这种句子越少分越高，一句都没有最高分。请牢记下面这条边界：

[坏 ✗ 这是在复述依据，会被扣分]"月销售额未超过10万元的小规模纳税人可以免征增值税，所以本月免征。"——第一句整句在介绍那条规定本身，等于把依据换个说法搬了一遍。
[好 ✓ 这是自己在推、把事实用进判断]"先看这个月卖了多少——9万；小规模这档免税线是10万，9万还在线里没踩，那这部分增值税就免了。"——没有一句在"介绍依据说了啥"，10万这个数字被直接当成判断依据用进了本题推导。

所以：事实依据只是你脑子里早就掌握的常识，你只能把里面的具体数字和口径【像判断条件一样自然用进推理】（"这档线是X，本题才Y、还在线内，所以……"），绝不能整句整段地去陈述某条规定本身、也绝不能逐条转述或归纳依据。

四条铁律，违反任何一条都算失败：
一、不复述。绝不出现"把依据某段换个说法重讲一遍"的句子；事实只能作为某一步判断的条件被带过，不能整句陈述规定本身，不能逐条转述/归纳/对照依据。
二、不检索腔。全程绝不出现：参考问答对、参考资料、参考内容、检索结果、原始问答对、资料显示/表明/指出、根据上述资料/以上资料/提供的资料、如上文/如前文/如前所述、问答对X、问题X：、回答：、逐条/依次/分别对照、小贴士、温馨提示、参考下图、如下图、您可以参考、亲、哦 等任何字眼或结构；不许成串罗列法规文号，更不许用"政策依据：/参考文件：/参考法规：/文件依据："这类标签起头甩文号。把某条法规或单个文号自然嵌进一句推理里引用一次（如"按《XX》的规定……"）是允许的，列两个以上文号清单不行。
三、事实与结论锁死。推理中出现的每一个税率、百分比、金额、数字、日期、期限，以及结论极性（免征/应缴、可以/不得、属于/不属于、超过/不超过、需缴/无需），都必须取自【事实依据】、并与【已锁定的结论】完全一致；绝不臆造依据里没有的新数字或新口径，绝不推出与结论相反或更宽/更严的判断，依据没给的细节就不展开。
四、只输出这段第一人称的思考过程本身，第一句就直接从题目切入；不写最终答案那句话，不要标题、标签、序号、引号、前后缀或任何解释。

宁可写得简短、句句在推，也不要为了显得专业而堆砌或多讲——多写的句子最容易变成在复述依据，反而丢分。"""

